/**
 * Содержимое страницы установки.
 *
 * ── Цен нет, и это рабочее состояние ──
 *
 * Здесь стояли цифры, снятые с сайта конкурента avtostil-spb.ru как
 * ориентир по рынку. Для вёрстки это годилось, для живого сайта — нет:
 * чужой прайс, выданный за свой, это цена, по которой к нам приедет
 * человек, и которую мы не обязаны держать.
 *
 * Перечень работ при этом настоящий — он описывает то, что сервис
 * действительно делает, и остаётся на месте. Пока цен нет, страница
 * показывает список работ и говорит, что стоимость называют по
 * телефону. Заполняется через админку.
 *
 * Формулировки описывают обычный порядок работ, а не обещают результат
 * в каждом случае: «обычно не требуется», «предупредим заранее». Иначе
 * это уже обязательство, за которое отвечает заказчик.
 */

