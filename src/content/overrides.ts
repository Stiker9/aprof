import table from '../../data/content-overrides.json'

/**
 * Правки владельца, применённые к содержимому сайта.
 *
 * ── Почему через файл, а не из базы напрямую ──
 *
 * Телефон и адрес выводятся на 8 251 странице, и берутся они из
 * обычной константы — синхронно, прямо при отрисовке. Чтобы читать их
 * из базы, каждую из этих страниц пришлось бы сделать асинхронной, а
 * заодно и шапку с подвалом, то есть почти весь сайт.
 *
 * Поэтому правки выкладываются в файл перед сборкой — скриптом
 * scripts/apply-overrides.ts. Константы остаются константами, а сборка
 * собирает страницы уже с новыми значениями.
 *
 * Приём в проекте не новый: так же собирается список товаров с
 * картинками (src/catalog/product-photos.ts).
 *
 * ── Почему JSON, а не сгенерированный модуль ──
 *
 * Сгенерированный .ts пришлось бы заново разбирать глазами при каждом
 * конфликте в git и типизировать вручную. JSON читается импортом,
 * занимает одну строку и в сборке ведёт себя так же.
 *
 * Файл обязан существовать всегда, пусть и пустым объектом: без него
 * падает не сборка, а разбор типов — то есть вся разработка.
 */
type Table = Record<string, Record<string, Record<string, string>>>

const OVERRIDES = table as Table

/**
 * Одно значение. `undefined`, если владелец это поле не трогал, —
 * тогда остаётся то, что написано в коде.
 *
 * Пустые строки отсеиваются: в базе их быть не должно (пустая правка
 * удаляется, а не сохраняется), но файл собирается скриптом, а скрипт
 * однажды ошибётся. Пустой телефон на 8 251 странице — слишком дорогая
 * цена за доверие к своему же скрипту.
 */
export function contentValue(entity: string, key: string, field: string): string | undefined {
  const value = OVERRIDES[entity]?.[key]?.[field]
  return value === undefined || value.trim() === '' ? undefined : value
}

/** Все правки одной сущности разом: ключ → поле → значение. */
export function contentGroup(entity: string): Record<string, Record<string, string>> {
  return OVERRIDES[entity] ?? {}
}
