import { clsx, type ClassValue } from 'clsx'
import { twMerge } from 'tailwind-merge'

/**
 * Склейка классов Tailwind с разрешением конфликтов.
 *
 * Заведена ради компонентов из внешних библиотек: они собираются под
 * shadcn и ждут `cn` именно по этому адресу. Полный `shadcn init` мы не
 * запускали намеренно — он переписывает globals.css и подставляет свои
 * токены цветов и радиусов поверх дизайн-системы из макета.
 *
 * twMerge поверх clsx нужен, чтобы поздний класс побеждал ранний:
 * clsx('p-2', 'p-4') оставит оба, и какой сработает — решит порядок в
 * готовом файле стилей, а не порядок в вызове.
 */
export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs))
}
