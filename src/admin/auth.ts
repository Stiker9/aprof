import { cache } from 'react'
import { redirect } from 'next/navigation'
import { readSession, type AdminSession } from './session'

/**
 * Единственная точка, через которую админка узнаёт, кто пришёл.
 *
 * ── Почему не proxy.ts ──
 *
 * Проверку входа принято ставить в proxy (бывшее middleware) — один
 * файл на все адреса. Здесь так нельзя: proxy.ts лежит в корне и
 * попадает в любую сборку, а сайт собирается в режиме `output: 'export'`,
 * где proxy не поддерживается вовсе — сборка витрины просто упала бы.
 *
 * Но и будь он доступен, одного proxy не хватило бы. Он отсекает заход
 * на страницу, а не вызов действия: серверное действие — это POST на
 * собственный адрес, и попасть в него можно мимо страницы. Поэтому
 * проверка стоит у данных, а не у маршрута, — как и советует
 * документация Next.
 *
 * ── Правило ──
 *
 * `requireAdmin()` вызывается в начале КАЖДОГО серверного действия и
 * каждой страницы админки. Не «в макете один раз»: макет и страница
 * рендерятся независимо, и действие не рендерится вовсе.
 *
 * `cache` из React склеивает повторные вызовы внутри одного запроса:
 * печенька разбирается однажды, даже если проверка стоит в пяти местах.
 */
export const requireAdmin = cache(async (): Promise<AdminSession> => {
  const session = await readSession()
  if (!session) redirect('/admin/vhod')
  return session
})

/**
 * Кто вошёл, без перенаправления.
 *
 * Нужна странице входа: вошедшего она отправляет внутрь, а не показывает
 * ему форму ещё раз.
 */
export const currentAdmin = cache(async (): Promise<AdminSession | null> => readSession())
