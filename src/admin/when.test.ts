import { expect, test } from 'vitest'
import { formatWhen } from './when'

// Полдень 15 октября 2026 по Москве — 09:00 UTC.
const now = new Date('2026-10-15T09:00:00Z')

test('сегодняшняя заявка — «сегодня» и время по Москве', () => {
  expect(formatWhen('2026-10-15T05:20:00Z', now)).toBe('сегодня, 08:20')
})

test('вчерашняя — «вчера»', () => {
  expect(formatWhen('2026-10-14T15:05:00Z', now)).toBe('вчера, 18:05')
})

test('давняя — число и месяц без года', () => {
  expect(formatWhen('2026-10-03T15:40:00Z', now)).toBe('3 октября, 18:40')
})

test('прошлогодняя — с годом', () => {
  expect(formatWhen('2025-06-10T09:00:00Z', now)).toBe('10 июня 2025, 12:00')
})

test('год приписывается по московному календарю, а не по UTC', () => {
  // 31 декабря 21:00 UTC — это уже 1 января по Москве, то есть нынешний
  // год, и года в подписи быть не должно.
  expect(formatWhen('2025-12-31T21:00:00Z', now)).toBe('1 января, 00:00')
})

test('московная полночь попадает в нужные сутки', () => {
  // 20:30 UTC — это уже 23:30 в Москве того же дня; ошибка в поясе
  // показала бы «вчера».
  expect(formatWhen('2026-10-14T20:30:00Z', now)).toBe('вчера, 23:30')
  // А 21:30 UTC 14-го — это 00:30 15-го по Москве, то есть «сегодня».
  expect(formatWhen('2026-10-14T21:30:00Z', now)).toBe('сегодня, 00:30')
})

test('испорченная дата возвращается как есть, а не падает', () => {
  expect(formatWhen('не дата', now)).toBe('не дата')
})
