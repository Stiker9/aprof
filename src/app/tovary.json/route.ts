import { buildFitmentIndex, listAllProductsCompact } from '@/catalog/queries'
import { getDb } from '@/db/client'

/**
 * Весь каталог одним файлом — для страницы подбора.
 *
 * Она фильтрует 5 808 позиций на клиенте, и держать их в разметке
 * страницы нельзя: это 420 килобайт в HTML на каждого посетителя, даже
 * на того, кто пришёл читать про установку. Отдельным файлом они
 * запрашиваются только при открытии подбора и дальше лежат в кеше.
 *
 * Вместе с товарами идут связки «кузов → товары»: на странице подбора
 * машину выбирают прямо в карточке фильтра, и список должен сузиться на
 * месте. Связки весят 22 килобайта в сжатом виде — дешевле, чем второй
 * запрос за ними же.
 *
 * Записи товаров — массивы, а не объекты: имена полей повторялись бы
 * 5 808 раз и весили больше самих значений.
 */
export const dynamic = 'force-static'

export async function GET() {
  const db = await getDb()
  const [products, fits] = await Promise.all([
    listAllProductsCompact(db),
    buildFitmentIndex(db),
  ])

  return Response.json(
    { products, fits },
    {
      headers: {
        /*
          Адрес постоянный, содержимое меняется с каждой выкладкой. С
          длинным сроком жизни браузер отдавал бы список от прошлой
          сборки, и подбор молча показывал бы снятые с продажи позиции.
          Перепроверка дешёвая: файл не изменился — приходит 304 без тела.
        */
        'cache-control': 'no-cache',
      },
    },
  )
}
