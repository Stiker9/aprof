/**
 * Урезание статической генерации на время работы над дизайном.
 *
 * Полная сборка выпускает 8260 страниц каталога — около четырёх минут
 * ожидания. Когда правишь вёрстку главной или общие компоненты, эти
 * страницы не нужны: проверить надо две-три, а не восемь тысяч.
 *
 * Переменная задаётся только вручную — `npm run build:design`. На
 * Vercel её нет, поэтому продакшн всегда собирается целиком, даже если
 * забыть про режим. Это важнее удобства: сборка, тихо выпустившая
 * двадцать страниц вместо восьми тысяч, выглядит как успешная.
 */
const LIMIT = 3

export const designMode = process.env.DESIGN_MODE === '1'

/** Оставляет первые несколько параметров маршрута, если режим включён. */
export function limitParams<T>(params: T[], route: string): T[] {
  if (!designMode) return params

  const kept = params.slice(0, LIMIT)
  console.warn(
    `DESIGN_MODE: ${route} — собрано ${kept.length} страниц из ${params.length}`,
  )
  return kept
}
