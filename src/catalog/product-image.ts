import { ballIconSrc } from '@/catalog/ball-icon'

/**
 * Какой снимок показывать в карточке товара.
 *
 * Все изображения — свои, из public/images/products. Ни одной ссылки
 * на чужой сервер здесь больше нет, и это главное правило файла.
 *
 * ── Почему правило именно такое ──
 *
 * Раньше чертёж брался прямой ссылкой на сервер поставщика:
 *
 *   <img src="https://xn--80aumecw.xn--p1ai/shema/F.6312.001.jpg">
 *
 * 3 630 карточек грузили картинку с чужого сервера при каждом
 * открытии. Владелец сервера видел по Referer, какие наши страницы
 * смотрят; мог закрыть доступ и разом оставить каталог без картинок;
 * мог подменить любое изображение своей рекламой. Скорость наших
 * страниц зависела от его сервера.
 *
 * Всё это скачано к себе скриптом scripts/images/schemas.ts.
 *
 * Заодно вскрылось, ради чего стоило: у 64 чертежей GALIA — завода,
 * который считался чистым, — поверх замощён красный «ФАРКОП.РФ» с
 * чужим телефоном. Они показывались на сайте и никем не были замечены,
 * потому что никто не открывал тысячу карточек подряд. Сейчас эти 64
 * не в списке и показывают обобщённый рисунок.
 *
 * ── Порядок предпочтения ──
 *
 * 1. `photo` — свой файл этого артикула: чертёж сборки, 3D-рендер или
 *    снимок изделия. Собран парсером с сайтов заводов и из выгрузки,
 *    просмотрен глазами, лежит у нас.
 *
 * 2. `icon` — обобщённый рисунок по типу шара. Ничего не утверждает
 *    про конкретный артикул и потому годится всегда.
 *
 * Третьего не дано намеренно: если своего файла нет, лучше честный
 * общий рисунок, чем ссылка наружу.
 */

export interface ProductDisplayImage {
  src: string
  /** 'photo' — своё изображение этого артикула, 'icon' — рисунок по типу шара. */
  kind: 'photo' | 'icon'
}

/**
 * Список товаров с картинками сюда НЕ импортируется.
 *
 * Эта функция вызывается и в клиентских компонентах — плитки на
 * странице подбора рисуются в браузере. Импорт списка утащил бы туда
 * все четыре тысячи слагов: 47 КБ лишнего JavaScript на каждой
 * странице каталога. Так и было ровно один деплой.
 *
 * Поэтому адрес приходит готовой строкой в ProductRow.photo: на сервере
 * его подставляет queries.ts, на клиенте — catalog-filter.tsx по биту
 * из подгружаемого файла.
 */
export function productDisplayImage(product: {
  photo: string | null
  ballType: string | null
}): ProductDisplayImage {
  if (product.photo) return { src: product.photo, kind: 'photo' }
  return { src: ballIconSrc(product.ballType), kind: 'icon' }
}
