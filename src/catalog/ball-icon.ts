/**
 * Обобщённый рисунок фаркопа по типу шара — используется, когда для
 * товара нет собственной схемы (см. product-image.ts).
 *
 * Форма узла подтверждена текстом описания у пяти типов — там она прямо
 * названа: AV и AH — быстросъёмный шар на ключе (вертикальный и
 * горизонтальный), C — горизонтальный съёмный без ключа, E и EA — узел
 * под американский квадрат (EA отличается только антистуком, на
 * рисунке этого размера это не видно, поэтому используют один и тот же
 * узел), H — сварное несъёмное крепление.
 *
 * Тип A формы в описаниях не называет, но код H прямо занят «сварным
 * несъёмным» — значит, A им не является, а единственная стандартная
 * альтернатива в отрасли — шар на болтах через площадку. Она и
 * нарисована.
 *
 * Тип F не редкий (около 250 позиций), но форму его узла ни описания,
 * ни это рассуждение не подтверждают. Рисовать её наугад — то же самое
 * фабрикование, которое мы убираем из каталога, поэтому F, как и любой
 * не перечисленный здесь код, получает нейтральный рисунок: балка и
 * шар без утверждений про сам узел.
 */
const BALL_ICON: Record<string, string> = {
  A: 'a',
  H: 'h',
  C: 'c',
  AH: 'ah',
  AV: 'av',
  E: 'e',
  EA: 'e',
}

export function ballIconSrc(ballType: string | null): string {
  const slug = (ballType && BALL_ICON[ballType]) || 'unknown'
  return `/images/ball/${slug}.svg`
}
