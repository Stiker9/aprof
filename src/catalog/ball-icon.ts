/**
 * Обобщённое изображение по типу шара — когда своего снимка артикула нет
 * (см. product-image.ts).
 *
 * Два сорта. Фотография узла, если заказчик её прислал; иначе рисунок.
 *
 * ── Фотографии ──
 *
 * Прислал заказчик, чтобы закрыть карточки, для которых снимка изделия
 * взять неоткуда: у AvtoS, Sheriff и Halty нет сайтов, а в выгрузке
 * поставщика всё заштамповано чужим знаком. Обрабатываются скриптом
 * scripts/images/ball-photos.ts.
 *
 * Он же дал два правила: «нет данных по шару — показывать A» и «шар H —
 * показывать A». Он ставит эти изделия каждый день, так что это знание,
 * а не догадка. Раньше у H был свой рисунок, а у неизвестных типов —
 * нейтральный; теперь оба ведут на снимок A.
 *
 * Подпись «обобщённое изображение» остаётся обязательной. Рисунок сам
 * себя выдавал схемой, фотография же читается как «вот этот самый
 * товар» — а это не он.
 *
 * ── Рисунки ──
 *
 * Форма узла подтверждена текстом описания у пяти типов — там она прямо
 * названа: AV и AH — быстросъёмный шар на ключе (вертикальный и
 * горизонтальный), C — горизонтальный съёмный без ключа, E и EA — узел
 * под американский квадрат (EA отличается только антистуком, на рисунке
 * этого размера это не видно, поэтому используют один и тот же узел).
 *
 * Тип F не редкий (около 250 позиций), но форму его узла ни описания,
 * ни данные не подтверждают. Рисовать её наугад — то же самое
 * фабрикование, которое мы убираем из каталога, поэтому F, как и любой
 * не перечисленный здесь код, получает нейтральный рисунок: балка и
 * шар без утверждений про сам узел.
 */

/**
 * Типы, для которых есть фотография узла.
 *
 * EA ведёт на снимок E по той же причине, по которой вёл на рисунок E:
 * американский квадрат тот же, отличие только в антистуке.
 *
 * C взят из снимка, подписанного заказчиком «BA». Такого кода у нас нет,
 * и сопоставление сделано не на глаз: все 25 артикулов, оканчивающихся
 * на «-BA» (TAVIALS), имеют тип шара C с описанием «горизонтальный
 * съёмный» — ровно то, что на снимке.
 */
const BALL_PHOTO: Record<string, string> = {
  A: 'a',
  H: 'a',
  E: 'e',
  EA: 'e',
  C: 'c',
  D2: 'd2',
}

/** Типы, для которых есть рисунок. Используется, когда фотографии нет. */
const BALL_ICON: Record<string, string> = {
  AH: 'ah',
  AV: 'av',
}

export function ballIconSrc(ballType: string | null): string {
  // Нет данных по шару — показываем A: правило заказчика.
  const code = ballType ?? 'A'

  const photo = BALL_PHOTO[code]
  if (photo) return `/images/ball/photo/${photo}.webp`

  const icon = BALL_ICON[code]
  return `/images/ball/${icon ?? 'unknown'}.svg`
}

/**
 * Фотография это или рисунок — от этого зависит, как показывать кадр.
 *
 * Рисунок ставится с большим полем и приглушённым, чтобы не спорить с
 * настоящими снимками в соседних плитках. Фотографию глушить не надо.
 */
export function ballIsPhoto(ballType: string | null): boolean {
  return Boolean(BALL_PHOTO[ballType ?? 'A'])
}
