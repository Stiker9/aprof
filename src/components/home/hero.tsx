import Image from 'next/image'
import Link from 'next/link'
import { formatNumber } from '@/catalog/format'
import { urls } from '@/catalog/urls'
import { PickerBar } from '@/components/picker-bar'

/**
 * Первый экран.
 *
 * Занимает всё окно целиком. Шапка лежит поверх и места в потоке не
 * занимает, поэтому вычитать её высоту не нужно — фотография доходит
 * до верхнего края и просвечивает сквозь стекло шапки. Нижний предел
 * нужен для низких окон: без него на ноутбуке с невысоким экраном
 * текст и числа налезали бы друг на друга.
 *
 * Кадр один — Prado на набережной. Раньше здесь было два кадра со
 * сменой по CSS-анимации (фаркоп крупным планом + Prado), но под
 * prefers-reduced-motion второй кадр навсегда перекрывал первый
 * (opacity:1 без анимации, оба absolute inset-0 — верхний по DOM-порядку
 * просто закрывал нижний), и то, какое фото окажется видно, зависело
 * от системной настройки анимации, а не от того, что мы хотели
 * показать. Один статичный кадр надёжнее.
 *
 * Градиент взят из исходника: слева почти непрозрачный, к 48% ширины
 * сходит на нет. Без него текст ложится прямо на кузов и пропадает.
 */
/*
  Плотность вдвое меньше прежней (было 0.9 / 0.55 / 0.12) — заказчик
  попросил открыть фотографию. Точки перелома не трогаем: они и задают
  форму, а не силу затемнения.
*/
const GRADIENT =
  'linear-gradient(90deg, rgba(8,8,9,0.45) 0%, rgba(8,8,9,0.28) 22%, rgba(8,8,9,0.06) 36%, rgba(8,8,9,0) 48%, rgba(8,8,9,0) 100%)'

const NUMBERS = [
  /*
    «в каталоге», а не «в наличии». Сюда подставляется общее число
    товаров — 5 808. В наличии из них 3 454, остальные под заказ на срок
    до полугода, и подпись «в наличии» была просто неправдой.
  */
  { value: null, caption: 'фаркопов в каталоге' },
  { value: '2 года', caption: 'гарантии на работы' },
  { value: '3 часа', caption: 'средняя установка' },
]

export function Hero({ productCount }: { productCount: number }) {
  return (
    <section className="relative h-[var(--screen-h)] min-h-[620px] overflow-hidden bg-bg text-ink">
      {/*
        Снимок 2560x1463 (1.75:1) чуть «выше» блока, который на экране
        1920x1080 близок к 2:1 — object-cover срезает по высоте около
        13 процентов. Точка обрезки смещена немного вниз от центра:
        сверху уходит лишнее небо, а крыша машины и фаркоп на бампере
        (он примерно на 58 процентах высоты кадра) остаются целиком при
        любой ширине окна.
      */}
      <Image
        src="/images/hero-prado-4k.webp"
        alt=""
        fill
        priority
        sizes="100vw"
        className="object-cover object-[55%_15%]"
      />
      <div className="pointer-events-none absolute inset-0" style={{ background: GRADIENT }} />

      {/*
        Строка подбора лежит на фотографии сразу под шапкой. Отступ берётся
        из той же переменной, что и высота шапки: подставь сюда число — и
        на телефоне, где шапка ниже, между ними осталась бы щель.
      */}
      <div className="absolute inset-x-0 top-[var(--header-h)] z-[5]">
        <PickerBar transparent />
      </div>

      {/*
        В исходнике этот блок не прижат к низу — у него отступ сверху
        `padding-top: clamp(140px,20vh,200px)` от верхнего края hero
        (ГЛАВНАЯ.dc.html, обёртка текста). Раньше здесь стояло
        `bottom-0 pb-*`, и текст прилипал к самому низу секции — на
        невысоком окне браузера это выглядело так, будто заголовок
        «висит внизу», почти без отступа от цифр до края.
      */}
      <div className="absolute inset-0 px-5 pt-[clamp(120px,18vh,180px)] pb-10 sm:px-8 lg:px-14 lg:pt-[clamp(140px,20vh,200px)] lg:pb-[clamp(28px,4vh,40px)]">
        <div className="max-w-[42%] min-w-[420px] max-lg:max-w-none">
          {/*
            Красная черта над заголовком. На первом экране акцент до этого
            жил только в кнопке подбора справа, и с левой колонкой ничем
            не был связан. Черта заводит его туда, не трогая ни текст, ни
            кнопку — заголовок остаётся единственным белым пятном.
          */}
          <span aria-hidden className="mb-6 block h-[3px] w-11 rounded-sm bg-accent" />
          <h1 className="font-[family-name:var(--font-display)] text-[clamp(30px,3.3vw,45px)] leading-[1.04] tracking-[-0.01em]">
            Фаркопы с установкой
            <br />в Санкт-Петербурге
          </h1>

          {/*
            Белый, а не серый #D8D8D5, как было. Затемнение фотографии
            уменьшено вдвое по просьбе заказчика, и на посветлевшем кадре
            серый провалился ниже нормы контраста. Осветляем текст, а не
            возвращаем затемнение: открыть фотографию и просили.
          */}
          <p className="mt-5 max-w-[46ch] text-[clamp(14px,1.1vw,17px)] leading-[1.5] text-white">
            Подберём по марке, модели и году. Поставим за один визит — с документами для ТО.
          </p>

          {/*
            Кнопка залита белым, а не обведена контуром, как в макете.

            Прежняя занимала 355 на 104 пикселя — больше красной кнопки в
            строке подбора, — но при прозрачной заливке и рамке в 55%
            белого терялась на фотографии. Дело было не в размере, а в
            весе, поэтому «сделать покрупнее» задачу бы не решило.

            Белая, а не красная: красная кнопка «Подобрать» уже стоит на
            200 пикселей выше, в строке подбора, и вторая такая же рядом
            читалась бы как дубль. Приём не выдуман — точно так же сделана
            кнопка «Записаться» в карточке акции.
          */}
          <Link
            href={urls.catalog()}
            className="mt-7 inline-flex items-center gap-2.5 self-start rounded-full bg-white px-7 py-[15px] text-[16px] font-semibold text-[#0D0D0E] transition-colors hover:bg-[#E8E6E1]"
          >
            Подобрать фаркоп <span aria-hidden className="text-accent">→</span>
          </Link>

          {/*
            Цифры крупнее, чем задано ролью «Цифра» в дизайн-системе — там
            22 пикселя флэтом. Подняты по просьбе заказчика: на первом
            экране это не справка, а доводы, и прежний размер их прятал.

            Верхний предел 32 держит их ниже заголовка (30–45): спорить
            с ним за внимание они всё равно не должны.
          */}
          <div className="mt-8 flex flex-wrap gap-x-7 gap-y-4">
            {NUMBERS.map((item) => (
              <div key={item.caption} className="flex flex-col gap-1.5">
                <span className="font-[family-name:var(--font-display)] text-[clamp(26px,2.1vw,32px)] leading-none">
                  {item.value ?? formatNumber(productCount)}
                </span>
                {/*
                  Подписи под цифрами — самый мелкий текст на экране, и
                  на посветлевшем кадре серый #9C9C9A давал 1,6:1 при
                  норме 4,5. Белый с лёгкой прозрачностью: заметно тише
                  самих цифр, но читается.
                */}
                <span className="text-xs text-white/90">{item.caption}</span>
              </div>
            ))}
          </div>
        </div>
      </div>
    </section>
  )
}
