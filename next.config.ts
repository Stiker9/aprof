import path from 'node:path'
import type { NextConfig } from 'next'

/**
 * Режим статической выгрузки — для виртуального хостинга.
 *
 * Включается переменной: STATIC_EXPORT=1 npm run build. Без неё сборка
 * идёт как раньше, серверной, — она нужна для разработки и пригодится,
 * когда сайт переедет на VPS вместе с админкой.
 *
 * Выгрузка кладёт в папку `out` готовые файлы: 8 262 страницы, картинки,
 * стили. Сервер для них не нужен, их раздаёт любой хостинг.
 */
const staticExport = process.env.STATIC_EXPORT === '1'

/**
 * Админка видна только в серверном режиме.
 *
 * Её страницы называются `page.admin.tsx`, и Next их не замечает, пока
 * расширение не разрешено явно. В статической выгрузке оно не
 * разрешено — значит админки там нет вовсе, а не «есть, но не
 * работает». Это важно: она пишет в базу и принимает пароль, и попасть
 * на публичный хостинг не должна ни одним файлом.
 *
 * Способ описан в документации Next как штатный (pageExtensions).
 */
const nextConfig: NextConfig = {
  ...(staticExport ? { output: 'export' as const } : {}),

  /**
   * Куда складывать сборку.
   *
   * По умолчанию `.next`. Но на сервере одновременно живут две сборки:
   * серверная — её крутит админка прямо сейчас, — и статическая, которую
   * собирают по кнопке «Опубликовать». Положи вторую туда же, и она
   * затрёт файлы работающей админки посреди запроса.
   *
   * Поэтому выгрузка собирается в свою папку: build-static.mjs
   * выставляет NEXT_DIST_DIR, и две сборки больше не пересекаются.
   */
  distDir: process.env.NEXT_DIST_DIR || '.next',

  pageExtensions: staticExport
    ? ['tsx', 'ts']
    : ['admin.tsx', 'admin.ts', 'tsx', 'ts'],

  /**
   * PGlite не должен попадать в бандл.
   *
   * Это PostgreSQL, скомпилированный в WebAssembly, и он сам разрешает пути
   * к своим файлам через файловую систему Node. Когда сборщик его упаковывает,
   * разрешение путей ломается: «The "path" argument must be of type string…
   * Received an instance of URL». Пакет должен грузиться как обычный внешний
   * модуль на стороне сервера.
   */
  serverExternalPackages: ['@electric-sql/pglite'],

  experimental: {
    /**
     * Генерация страниц идёт в один процесс.
     *
     * По умолчанию Next.js поднимает воркер на каждое ядро, и все они
     * одновременно открывают одну и ту же файловую базу PGlite. Это
     * однопоточный WebAssembly, конкурентный доступ он не держит и падает
     * с «RuntimeError: Aborted()». Сборка становится дольше, но проходит.
     */
    cpus: 1,
  },

  /**
   * Абсолютный путь к PGlite для ВСЕХ процессов сборки.
   *
   * «Collecting page data» у Next.js — это отдельный дочерний процесс
   * (см. cpus: 1 выше — воркер поднимается всё равно, просто один). Его
   * process.cwd() не гарантированно совпадает с тем, откуда запускался
   * npm run prebuild. Относительный './.pgdata' в src/db/client.ts тогда
   * резолвится в другое место — воркер тихо открывает НОВУЮ пустую базу
   * вместо развёрнутой prebuild-скриптом, и запрос падает с «relation
   * "variants" does not exist», хотя дамп на самом деле развернулся верно.
   *
   * next.config.ts заведомо перезагружается в каждом процессе (это видно
   * в логе сборки: «Running next.config.ts took ...»), и его __dirname —
   * всегда корень проекта, не зависит от cwd воркера. Поэтому путь
   * считаем именно здесь и раздаём через env — так client.ts и
   * restore-data.ts гарантированно смотрят в один и тот же каталог.
   */
  /**
   * Без верхних значений по умолчанию Next.js на широких мониторах
   * запрашивает у next/image версию шириной вплоть до 3840px. Ни один
   * снимок на сайте до такого размера не дотягивает — 3840 их только
   * растягивает сверх исходного, отсюда заметная размытость.
   *
   * Потолок 2560 выбран под hero: снимок для него делается 2560×1280
   * (соотношение 2:1 — ровно пропорции блока на экране 1920×1080, где
   * hero занимает всю высоту окна). Файл такого размера движок будет
   * уменьшать, а не растягивать, а это всегда чётче.
   */
  images: {
    deviceSizes: [640, 750, 828, 1080, 1200, 1920, 2560],
    /*
      В статической выгрузке подгонять картинку под экран некому: на
      виртуальном хостинге нет процесса, который это делал бы на лету.
      Поэтому каждый получает исходный файл — и поэтому исходники
      заранее ужаты до разумных размеров скриптом
      scripts/images/shrink-assets.ts.
    */
    unoptimized: staticExport,
  },

  env: {
    /*
      `||`, не `??`: в окружении Vercel PGLITE_PATH оказался задан пустой
      строкой (осталось от более раннего эксперимента в настройках
      проекта). Пустая строка — не undefined, `??` её не подменяет, и
      PGlite('') тихо переходит в режим «в памяти» — у каждого процесса
      сборки тогда своя, никак не связанная с остальными база. Именно
      это стояло за «relation "variants" does not exist» оба раза.
    */
    PGLITE_PATH: process.env.PGLITE_PATH || path.resolve(__dirname, '.pgdata'),
  },
}

export default nextConfig
