/**
 * Чертёж это или нет.
 *
 * Заводы кладут в карточку три сорта изображений: чертёж сборки или
 * 3D-рендер изделия на белом; рекламную плашку с диагоналями и крупным
 * артикулом; фотографию фаркопа на машине.
 *
 * Годится первый сорт. Он показывает сам товар, в кадре нет ничего
 * чужого, и вид совпадает со схемами, которые уже стоят у 63% карточек.
 * Фотография опаснее всех: в кадр попадают номера и рамки номера с
 * телефонами автосалонов. Это не теория — на снимке Трейлера к артикулу
 * 2020 читается «MAJOR AUTO … 229-46-46», на снимке Лидер-плюс к A201-A
 * телефон ростовского дилера Honda.
 *
 * ── Почему считается именно так ──
 *
 * Первая версия смотрела на долю белого и общую насыщенность — и
 * попалась. Фотографию фаркопа вырезают из фона и кладут на белое:
 * белого на ней столько же, сколько на чертеже, а насыщенность
 * размазывается тем же белым до нуля. Тот снимок Datsun прошёл насквозь
 * и попал бы в каталог.
 *
 * Различает их не цвет, а сложность. У чертежа десяток плоских заливок,
 * у фотографии — тысячи оттенков с шумом и градиентами. Замеры на живых
 * файлах, сетка 96×96, цвета огрублены до 12 бит:
 *
 *   чертёж сборки Лидер-плюс     белого 0.77   цветов  33   энтропия 1.91
 *   рендер Трейлер               белого 0.91   цветов  29   энтропия 1.25
 *   рендер Трейлер (9651)        белого 0.82   цветов  19   энтропия 1.47
 *   фото на белом (2020)         белого 0.53   цветов 160   энтропия 4.66
 *   фото на белом (7740)         белого 0.53   цветов 112   энтропия 4.51
 *   рекламная плашка             белого 0.11   цветов 384   энтропия 6.83
 *   фото на машине               белого 0.18   цветов 339   энтропия 7.25
 *
 * Между чертежом и ближайшей к нему фотографией разрыв втрое по цветам
 * и вдвое по энтропии. Порог проходит посередине.
 *
 * Плашку от фотографии эти числа по-прежнему не отличают — и не надо:
 * всё, что не чертёж, идёт в `other` и ждёт просмотра глазами. Врать о
 * точности классификатора хуже, чем признать, что он умеет одно.
 */
import sharp from 'sharp'

export type ImageKind = 'drawing' | 'other'

export interface ImageProbe {
  kind: ImageKind
  width: number
  height: number
  /** Доля точек, где все три канала выше 235. */
  whiteRatio: number
  /** Сколько разных цветов в небелой части, огрублённо до 12 бит. */
  colours: number
  /** Энтропия по sharp: мера «сколько в картинке всего происходит». */
  entropy: number
}

/** Чертёж — светлый лист. Тёмный кадр на нашей плитке смотрелся бы дырой. */
const MIN_WHITE = 0.35
/** Втрое ниже самой бедной фотографии из замеров и вдвое выше самого пёстрого чертежа. */
const MAX_COLOURS = 60
const MAX_ENTROPY = 3

export async function probe(data: Buffer): Promise<ImageProbe | null> {
  let meta: Awaited<ReturnType<ReturnType<typeof sharp>['metadata']>>
  let entropy: number
  try {
    meta = await sharp(data).metadata()
    entropy = (await sharp(data).stats()).entropy
  } catch {
    return null
  }
  if (!meta.width || !meta.height) return null

  // Прозрачность кладём на белое — иначе PNG-рендер на прозрачном фоне
  // посчитается чёрным и уедет в `other`.
  const raw = await sharp(data)
    .flatten({ background: '#ffffff' })
    .resize(96, 96, { fit: 'fill' })
    .raw()
    .toBuffer()

  let white = 0
  const colours = new Set<number>()
  const pixels = raw.length / 3

  for (let i = 0; i < raw.length; i += 3) {
    const r = raw[i]
    const g = raw[i + 1]
    const b = raw[i + 2]
    if (Math.min(r, g, b) > 235) {
      white++
      continue
    }
    // Огрубляем до 4 бит на канал: иначе шум сжатия сам по себе даёт
    // тысячи «разных» цветов и чертёж не отличить от фотографии.
    colours.add(((r >> 4) << 8) | ((g >> 4) << 4) | (b >> 4))
  }

  const whiteRatio = white / pixels
  const kind: ImageKind =
    whiteRatio >= MIN_WHITE && colours.size <= MAX_COLOURS && entropy < MAX_ENTROPY
      ? 'drawing'
      : 'other'

  return { kind, width: meta.width, height: meta.height, whiteRatio, colours: colours.size, entropy }
}
