/**
 * Договор между ядром парсера и адаптером завода.
 *
 * Ядро одинаково для всех: очередь, паузы, кэш, скачивание, разбор
 * картинки, запись в манифест. Адаптер знает только своё — как у этого
 * завода устроен каталог и где на странице лежит артикул.
 *
 * Так добавление нового завода стоит один файл на полсотни строк, а не
 * копию всего конвейера.
 */

export interface SourceImage {
  url: string
  /** Страница, с которой картинка взята: часть серверов без него отдают заглушку. */
  referer?: string
}

export interface SourceProduct {
  /** Артикул так, как он написан на сайте завода. */
  article: string
  pageUrl: string
  /** В порядке появления на странице: первым идёт то, что завод считает главным. */
  images: SourceImage[]
}

export interface DiscoverContext {
  /**
   * Ключи артикулов, которым ещё нужна картинка.
   *
   * Адаптер вправе на них опереться и не разбирать страницы товаров,
   * которых у нас нет: у Лидер-плюс в каталоге 743 карточки, а нужны
   * нам 379.
   */
  needed: Set<string>
  /** Ограничение на число разобранных карточек — для отладки адаптера. */
  limit?: number
}

export interface Source {
  /** Короткое имя, оно же папка кэша и колонка в отчёте. */
  id: string
  /** Адрес завода — попадает в отчёт, чтобы источник каждой картинки был виден. */
  site: string
  /** Названия производителей в нашей базе, к которым этот источник применим. */
  manufacturers: string[]
  discover(ctx: DiscoverContext): AsyncGenerator<SourceProduct>
}
